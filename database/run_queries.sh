#!/usr/bin/env bash
# Runs the SQL and MongoDB queries inside the Docker containers and saves the
# output to database/query_results.md. Run after scripts/load_data.py.
set -euo pipefail
cd "$(dirname "$0")"

{
  echo "# Query results"
  echo
  echo "Generated by \`database/run_queries.sh\` on the full cleaned dataset (531,208 transaction lines)."
  echo
  echo "## MySQL (\`sql/queries.sql\`)"
  echo
  echo '```'
  docker compose exec -T mysql mysql -uretail -pretail retail -t -vvv < sql/queries.sql 2>/dev/null \
    | grep -v -e '^Bye' -e 'rows* in set' -e 'Query OK' -e '^--------------$' | cat -s
  echo '```'
  echo
  echo "## MongoDB (\`mongodb/queries.js\`)"
  echo
  echo '```'
  docker compose cp mongodb/queries.js mongo:/tmp/queries.js >/dev/null 2>&1
  docker compose exec -T mongo mongosh retail --quiet --file /tmp/queries.js
  echo '```'
} > query_results.md

echo "Saved database/query_results.md"
